FORBIDDEN = ("\u201c", "\u201d", "\u2018", "\u2019", "\u2026")


def build_and_validate() -> bool:
    data = json.loads(TARGET_FILE.read_text(encoding="utf-8"))
    sections = data["sections"]

    total_keys = 0
    total_translated = 0
    errors: list[str] = []

    for sec_name, sec_dict in sections.items():
        if sec_name not in TRANSLATIONS:
            errors.append(f"Missing section in TRANSLATIONS: {sec_name}")
            continue
        trans_sec = TRANSLATIONS[sec_name]
        for key, value in sec_dict.items():
            if key.startswith("_"):
                continue
            total_keys += 1
            if key not in trans_sec:
                errors.append(f"Missing key in TRANSLATIONS: [{sec_name}][{key}]")
                continue

            th = trans_sec[key]
            en = value.get("en", "")

            if not th.strip():
                errors.append(f"Empty translation: [{sec_name}][{key}]")

            for ch in FORBIDDEN:
                if ch in th:
                    errors.append(f"Forbidden character in [{sec_name}][{key}]: {th}")

            try:
                for byte in th.encode("cp874"):
                    if not (byte < 128 or 161 <= byte <= 251):
                        errors.append(
                            f"Byte {byte} out of CP874 range in [{sec_name}][{key}]: {th}"
                        )
            except UnicodeEncodeError as error:
                errors.append(f"CP874 encode error in [{sec_name}][{key}]: {error}")

            if (len(en) - len(en.lstrip(" "))) != (len(th) - len(th.lstrip(" "))):
                errors.append(f"Leading space mismatch in [{sec_name}][{key}]")
            if (len(en) - len(en.rstrip(" "))) != (len(th) - len(th.rstrip(" "))):
                errors.append(f"Trailing space mismatch in [{sec_name}][{key}]")

            value["th"] = th
            total_translated += 1

    for sec_name, trans_sec in TRANSLATIONS.items():
        if sec_name not in sections:
            errors.append(f"Extra section in TRANSLATIONS: {sec_name}")
            continue
        for key in trans_sec:
            if key not in sections[sec_name]:
                errors.append(f"Extra key in TRANSLATIONS: [{sec_name}][{key}]")

    if errors:
        print(f"FAILED with {len(errors)} errors:")
        for error in errors:
            print(f"  - {error}")
        return False

    print(f"Validated all {total_translated}/{total_keys} strings successfully.")

    with open(TARGET_FILE, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(f"Successfully updated {TARGET_FILE}")
    return True


if __name__ == "__main__":
    import sys

    sys.exit(0 if build_and_validate() else 1)
